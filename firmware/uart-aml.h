/* ACPI 6.5 §§6.2.2, 6.4.3.5.3; resource layout reused from
 * firmware/fw-acpi-aml.c. One polling UART, no fabricated IRQ. */
#ifndef IA64_FIRMWARE_UART_AML_H
#define IA64_FIRMWARE_UART_AML_H
#include <stdint.h>
#include <stddef.h>
static inline size_t uart_aml_build(uint8_t *out, size_t capacity, uint64_t base)
{
    static const uint8_t aml[] = {
        0x10, 0x4f, 0x05, 0x5c, 0x5f, 0x53, 0x42, 0x5f, 0x5b, 0x82, 0x46, 0x05, 0x55, 0x41,
        0x52, 0x30, 0x08, 0x5f, 0x48, 0x49, 0x44, 0x0c, 0x41, 0xd0, 0x05, 0x01, 0x08, 0x5f,
        0x55, 0x49, 0x44, 0x00, 0x08, 0x5f, 0x53, 0x54, 0x41, 0x0a, 0x0f, 0x08, 0x5f, 0x43,
        0x52, 0x53, 0x11, 0x33, 0x0a, 0x30, 0x8a, 0x2b, 0x00, 0x00, 0x0d, 0x01, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x79, 0x00,
    };
    if (capacity < sizeof(aml))
        return 0;
    for (size_t i = 0; i < sizeof(aml); ++i)
        out[i] = aml[i];
    for (unsigned i = 0; i < 8; ++i)
        out[62 + i] = (uint8_t)((uint64_t)(base) >> (i * 8));
    for (unsigned i = 0; i < 8; ++i)
        out[70 + i] = (uint8_t)((uint64_t)(base + 7) >> (i * 8));
    for (unsigned i = 0; i < 8; ++i)
        out[86 + i] = (uint8_t)((uint64_t)(8) >> (i * 8));
    return sizeof(aml);
}
#endif
