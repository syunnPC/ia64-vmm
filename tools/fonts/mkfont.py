"""Generate 8x16 ASCII cells from public-domain X.Org misc-fixed 9x15 BDF.

Usage: mkfont.py 9x15.bdf output.h
The ninth column is cropped and baseline aligned to row 12, following the
conversion used by ia64-dos/tools/mkvgafont.py. No external Python modules.
"""

import pathlib
import sys


def generate(source, output):
    glyphs = {}
    lines = iter(pathlib.Path(source).read_text(encoding="ascii").splitlines())
    ascent = 12
    for line in lines:
        words = line.split()
        if not words:
            continue
        if words[0] == "FONT_ASCENT":
            ascent = int(words[1])
        elif words[0] == "ENCODING":
            code = int(words[1])
        elif words[0] == "BBX":
            w, h, x, y = map(int, words[1:])
        elif words[0] == "BITMAP":
            rows = []
            for row in lines:
                if row == "ENDCHAR":
                    break
                rows.append(int(row, 16))
            cell = [0] * 16
            for i, bits in enumerate(rows):
                r = 12 - y - h + i
                value = bits << (16 - 8 * ((w + 7) // 8))
                value = value >> x if x >= 0 else value << -x
                if 0 <= r < 16:
                    cell[r] = (value >> 8) & 255
            glyphs[code] = cell
    assert ascent <= 16
    cells = [glyphs[c] for c in range(0x20, 0x7F)]
    cells.append(glyphs.get(0xFFFD, glyphs[ord("?")]))
    text = (
        "/* SPDX-License-Identifier: GPL-2.0-or-later */\n"
        "/* Generated by tools/fonts/mkfont.py from X.Org misc-fixed 9x15.bdf.\n"
        " * Glyphs are public domain; see docs/fonts.md. */\n"
        "static const uint8_t console_font[96][16] = {\n"
    )
    for code, cell in enumerate(cells, 0x20):
        text += "    {" + ",".join(f"0x{v:02x}" for v in cell) + f"}}, /* {code:02x} */\n"
    pathlib.Path(output).write_text(text + "};\n", encoding="ascii")


if __name__ == "__main__":
    generate(*sys.argv[1:])
