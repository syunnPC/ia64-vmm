"""Assemble tools/vbios/guest_stub.S (the guest's F000h stub
segment) and emit its bytes as the C table
platform/vbios_guest_stub.inc, so the VMM build needs no x86 assembler.

  gen_guest_stub.py            write platform/vbios_guest_stub.inc
  gen_guest_stub.py --table F  write the C table to F instead
  gen_guest_stub.py --binary F write the 64 KiB segment the source defines

HOSTCC, OBJCOPY and NM name the host tools (defaults gcc, objcopy, nm).
"""

import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "tools/vbios/guest_stub.S"
TABLE = ROOT / "platform/vbios_guest_stub.inc"
ENTRIES = {
    "last_bus": "VBIOS_GUEST_LAST_BUS",
    "int1a": "VBIOS_GUEST_INT1A",
    "unsupported_service": "VBIOS_GUEST_UNSUPPORTED",
    "int10_trace": "VBIOS_GUEST_TRACE",
    "trace_end": "VBIOS_GUEST_TRACE_END",
    "trace_target": "VBIOS_GUEST_TRACE_TARGET",
}


def tool(name, default):
    return os.environ.get(name) or default


def assemble():
    """The segment's bytes (padded to 64 KiB) and the entry offsets."""
    with tempfile.TemporaryDirectory() as temp:
        obj, raw = Path(temp) / "stub.o", Path(temp) / "stub.bin"
        subprocess.run([tool("HOSTCC", "gcc"), "-c", "-o", str(obj), str(SOURCE)], check=True)
        relocations = subprocess.run(
            [tool("OBJDUMP", "objdump"), "-r", str(obj)], check=True, capture_output=True, text=True
        ).stdout
        if "R_X86" in relocations:
            raise SystemExit("guest_stub.S must assemble without relocations")
        subprocess.run(
            [tool("OBJCOPY", "objcopy"), "-O", "binary", "-j", ".text", str(obj), str(raw)],
            check=True,
        )
        symbols = {}
        for line in subprocess.run(
            [tool("NM", "nm"), str(obj)], check=True, capture_output=True, text=True
        ).stdout.splitlines():
            value, _, name = line.split()
            symbols[name] = int(value, 16)
        data = raw.read_bytes()
    if len(data) > 0x10000:
        raise SystemExit("stub segment exceeds 64 KiB")
    return data.ljust(0x10000, b"\0"), {macro: symbols[name] for name, macro in ENTRIES.items()}


def chunks(data):
    """Nonzero runs, joined across gaps shorter than 16 zero bytes."""
    result, at = [], 0
    while at < len(data):
        if not data[at]:
            at += 1
            continue
        end = at
        while end < len(data) and any(data[end : end + 16]):
            end += 1
        while not data[end - 1]:
            end -= 1
        result.append((at, data[at:end]))
        at = end
    return result


def table(data, entries):
    lines = [
        "/* SPDX-License-Identifier: GPL-2.0-or-later */",
        "/* Generated by tools/vbios/gen_guest_stub.py from tools/vbios/guest_stub.S;",
        " * do not edit; regenerate after assembly changes. The guest F000h stub segment:",
        " * these runs at their offsets, zero elsewhere. */",
    ]
    for macro, value in entries.items():
        lines.append(f"#define {macro} 0x{value:04x}u")
    runs = chunks(data)
    for index, (offset, body) in enumerate(runs):
        lines.append(f"static const uint8_t vbios_guest_run{index}[] = {{")
        for i in range(0, len(body), 12):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in body[i : i + 12]) + ",")
        lines.append("};")
    lines.append(
        "static const struct { uint16_t offset, length; const uint8_t *bytes; } vbios_guest_runs[] = {"
    )
    for index, (offset, body) in enumerate(runs):
        lines.append(f"    {{0x{offset:04x}, {len(body)}, vbios_guest_run{index}}},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--binary", type=Path)
    parser.add_argument("--table", type=Path, default=TABLE)
    args = parser.parse_args()
    data, entries = assemble()
    if args.binary:
        args.binary.write_bytes(data)
        return 0
    args.table.write_text(table(data, entries))
    print(f"wrote {args.table}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
