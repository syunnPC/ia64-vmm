const struct t1_helper_row *t1_helper_row(Ia64Opcode op)
{
    return (unsigned)op < IA64_OP_COUNT && rows[op].cls ? &rows[op] : NULL;
}

static unsigned slot(const struct t1_insn *ti, unsigned s)
{
    const IA64CommonOperands *o = &ti->insn.operands.common;
    switch (s) {
    case T1_HS_R1:
        return o->destination;
    case T1_HS_R2:
        return o->source1;
    case T1_HS_R3:
        return o->source2;
    case T1_HS_P1:
        return o->auxiliary1;
    case T1_HS_P2:
        return o->auxiliary2;
    default:
        return 0;
    }
}
static void add(uint16_t *e, unsigned *n, unsigned v)
{
    if (!v)
        return;
    for (unsigned k = 0; k < *n; ++k)
        if (e[k] == v)
            return;
    e[(*n)++] = (uint16_t)v;
}
static void gr_pair(const struct t1_insn *ti, unsigned logical, uint16_t *e, unsigned *n)
{
    /* Resolve with the formation contract: the instruction already carries
     * the resolved r1/r2/r3 fields, with BOF excluded. */
    unsigned v = logical == ti->insn.operands.common.destination ? ti->dst
                 : logical == ti->insn.operands.common.source1   ? ti->src1
                                                                 : ti->src2;
    if (v) {
        add(e, n, T1_ELEMENT_GR(v));
        add(e, n, T1_ELEMENT_NAT(v));
    }
}
unsigned t1_helper_elements(const struct t1_insn *ti, bool write, uint16_t *e)
{
    const struct t1_helper_row *h = t1_helper_row(ti->insn.opcode);
    unsigned n = 0;
    /* alloc (helper.c, the one that spills): r1 = ar.pfs, NaT clear. */
    if (ti->cls == T1_IC_ALLOC) {
        if (write) {
            add(e, &n, T1_ELEMENT_GR(ti->dst));
            add(e, &n, T1_ELEMENT_NAT(ti->dst));
        } else
            add(e, &n, T1_ELEMENT_PFS);
        return n;
    }
    if (!h)
        return 0;
    if (!write && ti->qp)
        add(e, &n, T1_ELEMENT_PR(ti->qp));
    const struct t1_hset *s = write ? h->write : h->read;
    unsigned count = write ? h->nwrite : h->nread;
    for (unsigned k = 0; k < count; ++k) {
        if (s[k].loc == T1_HL_FR) {
            unsigned logical = slot(ti, s[k].slot);
            unsigned f = ti->fr[s[k].slot == T1_HS_R1   ? 0
                                : s[k].slot == T1_HS_R2 ? 1
                                : s[k].slot == T1_HS_R3 ? 2
                                                        : 3];
            if (logical >= 2) {
                add(e, &n, T1_ELEMENT_FR(f));
                add(e, &n, T1_ELEMENT_FR_META(f));
            }
        } else if (s[k].loc == T1_HL_PSR_MF)
            add(e, &n, T1_ELEMENT_PSR_MF);
        else if (s[k].loc == T1_HL_PR) {
            unsigned q = s[k].slot == T1_HS_P1 ? ti->p1 : ti->p2;
            if (q)
                add(e, &n, T1_ELEMENT_PR(q));
        } else if (s[k].loc == T1_HL_GR)
            gr_pair(ti, slot(ti, s[k].slot), e, &n);
        else if (s[k].loc == T1_HL_AR && slot(ti, s[k].slot) == AR_LC)
            add(e, &n, T1_ELEMENT_LC);
        else if (s[k].loc == T1_HL_AR && slot(ti, s[k].slot) == AR_PFS)
            add(e, &n, T1_ELEMENT_PFS);
        else if (s[k].loc == T1_HL_AR && slot(ti, s[k].slot) == AR_EC)
            add(e, &n, T1_ELEMENT_EC);
        else if (s[k].loc == T1_HL_BR)
            add(e, &n, T1_ELEMENT_BR(slot(ti, s[k].slot) & 7));
        else if (s[k].loc == T1_HL_PR_ALL)
            for (unsigned p = 1; p < 64; ++p)
                add(e, &n, T1_ELEMENT_PR(p));
    }
    if (h->cls == T1_HC_M && (ti->insn.reg_base_update || ti->insn.imm_base_update)) {
        gr_pair(ti, ti->insn.operands.memory.base, e, &n);
        if (!write && ti->insn.reg_base_update)
            gr_pair(ti, ti->insn.operands.memory.source, e, &n);
    }
    bool partial = ti->insn.opcode == IA64_OP_MOV_GRPR ||
                   ti->insn.opcode == IA64_OP_MOV_PR_ROT_IMM ||
                   (ti->insn.opcode >= IA64_OP_LD1C_CLR && ti->insn.opcode <= IA64_OP_LD8C_NC);
    if (!write) {
        uint16_t writes[T1_N_ELEMENTS];
        unsigned nw = t1_helper_elements(ti, true, writes);
        /* An unconditional helper can preserve an FR (e.g. ld.c).
         * Sync cached FR halves even when qp is p0 before reloading W. */
        for (unsigned k = 0; k < nw; ++k)
            if (ti->qp || partial ||
                (writes[k] >= T1_ELEMENT_FR(2) && writes[k] <= T1_ELEMENT_FR(127)) ||
                (writes[k] >= T1_ELEMENT_FR_META(2) && writes[k] <= T1_ELEMENT_FR_META(127)))
                add(e, &n, writes[k]);
    }
    return n;
}
