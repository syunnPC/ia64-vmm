"""Expected bytes for tests/tier1/unit_x86enc.c.

Assembles one Intel-syntax line per case with the host GNU as (from PATH)
and prints the C rows of unit_x86enc.c's table: the encoder input, the
bytes GNU as produced and objdump's disassembly as a comment. The table in
the C file was generated by this script; rerun it and diff to audit:
    python3 -I tests/tier1/x86enc_expect.py | diff - <(sed -n '/BEGIN ROWS/,/END ROWS/p' \
        tests/tier1/unit_x86enc.c | sed '1d;$d')
Shift counts include the implicit count-one encoding and its neighboring
immediate forms. Accumulator immediates include both the imm8 and
accumulator forms, with boundary values for sign extension.
"""

import os, re, shutil, subprocess, tempfile

R = [
    "rax",
    "rcx",
    "rdx",
    "rbx",
    "rsp",
    "rbp",
    "rsi",
    "rdi",
    "r8",
    "r9",
    "r10",
    "r11",
    "r12",
    "r13",
    "r14",
    "r15",
]
R32 = [
    "eax",
    "ecx",
    "edx",
    "ebx",
    "esp",
    "ebp",
    "esi",
    "edi",
    "r8d",
    "r9d",
    "r10d",
    "r11d",
    "r12d",
    "r13d",
    "r14d",
    "r15d",
]
R16 = [
    "ax",
    "cx",
    "dx",
    "bx",
    "sp",
    "bp",
    "si",
    "di",
    "r8w",
    "r9w",
    "r10w",
    "r11w",
    "r12w",
    "r13w",
    "r14w",
    "r15w",
]
R8 = [
    "al",
    "cl",
    "dl",
    "bl",
    "spl",
    "bpl",
    "sil",
    "dil",
    "r8b",
    "r9b",
    "r10b",
    "r11b",
    "r12b",
    "r13b",
    "r14b",
    "r15b",
]
NOREG = None


def mem(base, index=None, scale=0, disp=0):
    return (base, index, scale, disp)


def masm(m, size):
    b, i, s, d = m
    parts = []
    if b is not None:
        parts.append(R[b])
    if i is not None:
        parts.append("%s*%d" % (R[i], 1 << s))
    txt = "+".join(parts)
    if d or not parts:
        if txt:
            txt += ("+%d" % d) if d >= 0 else ("-%d" % -d)
        else:
            txt = "%d" % d
    return "%s [%s]" % (size, txt)


MEMS = [
    mem(0),
    mem(4),
    mem(5),
    mem(12),
    mem(13),
    mem(3, disp=8),
    mem(3, disp=-128),
    mem(3, disp=0x80),
    mem(3, disp=0x12345),
    mem(3, 1, 3, 16),
    mem(14, 11, 2, -8),
    mem(13, 12, 1, 0),
    mem(None, 1, 1, 0x100),
    mem(None, None, 0, 0x1000),
    mem(4, 13, 3, 0x7FFFFFFF),
]
cases = []  # (c op, opnd0 C, opnd1 C, mem C or None, asm)


def add(op, asm, o0="{0, 0}", o1="{0, 0}", m=None):
    cases.append((op, o0, o1, m, asm))


def reg(r):
    return "{T1_%s, 0}" % R[r].upper()


def imm(v):
    return "{0, %s}" % (("INT64_C(%d)" % v) if v >= 0 else ("-INT64_C(%d)" % -v))


REGPAIRS = [(0, 3), (8, 15), (12, 5), (4, 13), (7, 9)]
for a, b in REGPAIRS:
    add("T1_X86_MOV64_RR", "mov %s, %s" % (R[a], R[b]), reg(a), reg(b))
    add("T1_X86_MOV32_RR", "mov %s, %s" % (R32[a], R32[b]), reg(a), reg(b))
    for op, mn in [
        ("ADD", "add"),
        ("SUB", "sub"),
        ("AND", "and"),
        ("OR", "or"),
        ("XOR", "xor"),
        ("CMP", "cmp"),
        ("TEST", "test"),
    ]:
        add("T1_X86_%s64_RR" % op, "%s %s, %s" % (mn, R[a], R[b]), reg(a), reg(b))
    add("T1_X86_IMUL64_RR", "imul %s, %s" % (R[a], R[b]), reg(a), reg(b))
    add("T1_X86_CMP32_RR", "cmp %s, %s" % (R32[a], R32[b]), reg(a), reg(b))
    add("T1_X86_TEST32_RR", "test %s, %s" % (R32[a], R32[b]), reg(a), reg(b))
    add("T1_X86_MOVZX32_8", "movzx %s, %s" % (R32[a], R8[b]), reg(a), reg(b))
    add("T1_X86_MOVZX32_16", "movzx %s, %s" % (R32[a], R16[b]), reg(a), reg(b))
    add("T1_X86_MOVSX64_8", "movsx %s, %s" % (R[a], R8[b]), reg(a), reg(b))
    add("T1_X86_MOVSX64_16", "movsx %s, %s" % (R[a], R16[b]), reg(a), reg(b))
    add("T1_X86_MOVSX64_32", "movsxd %s, %s" % (R[a], R32[b]), reg(a), reg(b))
    add("T1_X86_CMOV64 + 12", "cmovl %s, %s" % (R[a], R[b]), reg(a), reg(b))
    add("T1_X86_SET8 + 12", "setl %s" % R8[b], reg(b))
for r in [0, 1, 4, 13, 15]:
    for v in [-1, 127, -128, 128, -129, -0x80000000, 0x7FFFFFFF]:
        for op, mn in [
            ("ADD", "add"),
            ("ADC", "adc"),
            ("SUB", "sub"),
            ("AND", "and"),
            ("OR", "or"),
            ("XOR", "xor"),
            ("CMP", "cmp"),
        ]:
            add("T1_X86_%s64_RI" % op, "%s %s, %d" % (mn, R[r], v), reg(r), imm(v))
        add("T1_X86_CMP32_RI", "cmp %s, %d" % (R32[r], v), reg(r), imm(v))
        add("T1_X86_TEST64_RI", "test %s, %d" % (R[r], v), reg(r), imm(v))
        add("T1_X86_MOV64_RI32", "mov %s, %d" % (R[r], v), reg(r), imm(v))
    add("T1_X86_MOV32_RI32", "mov %s, 0x87654321" % R32[r], reg(r), imm(0x87654321))
    add(
        "T1_X86_MOV64_RI64",
        "movabs %s, 0x123456789abcdef0" % R[r],
        reg(r),
        "{0, (int64_t)UINT64_C(0x123456789abcdef0)}",
    )
    add("T1_X86_ZERO32", "xor %s, %s" % (R32[r], R32[r]), reg(r))
    for op, mn in [("NOT64", "not"), ("NEG64", "neg"), ("INC64_R", "inc")]:
        add("T1_X86_" + op, "%s %s" % (mn, R[r]), reg(r))
    for op, mn in [("SHL", "shl"), ("SHR", "shr"), ("SAR", "sar")]:
        for c in [0, 1, 2, 63]:
            add("T1_X86_%s64_RI" % op, "%s %s, %d" % (mn, R[r], c), reg(r), imm(c))
        add("T1_X86_%s64_RCL" % op, "%s %s, cl" % (mn, R[r]), reg(r), reg(1))
    add("T1_X86_CALL_R", "call %s" % R[r], reg(r))
    add("T1_X86_PUSH64_R", "push %s" % R[r], reg(r))
    add("T1_X86_POP64_R", "pop %s" % R[r], reg(r))
for k, m in enumerate(MEMS):
    for r in [[0, 6, 11][k % 3]]:
        add("T1_X86_LOAD64", "mov %s, %s" % (R[r], masm(m, "qword ptr")), reg(r), "{0, 0}", m)
        add("T1_X86_LOAD32", "mov %s, %s" % (R32[r], masm(m, "dword ptr")), reg(r), "{0, 0}", m)
        add("T1_X86_LOAD16ZX", "movzx %s, %s" % (R32[r], masm(m, "word ptr")), reg(r), "{0, 0}", m)
        add("T1_X86_LOAD8ZX", "movzx %s, %s" % (R32[r], masm(m, "byte ptr")), reg(r), "{0, 0}", m)
        add("T1_X86_STORE64", "mov %s, %s" % (masm(m, "qword ptr"), R[r]), "{0, 0}", reg(r), m)
        add("T1_X86_STORE32", "mov %s, %s" % (masm(m, "dword ptr"), R32[r]), "{0, 0}", reg(r), m)
        add("T1_X86_STORE16", "mov %s, %s" % (masm(m, "word ptr"), R16[r]), "{0, 0}", reg(r), m)
        add("T1_X86_STORE8", "mov %s, %s" % (masm(m, "byte ptr"), R8[r]), "{0, 0}", reg(r), m)
        add("T1_X86_LEA64", "lea %s, %s" % (R[r], masm(m, "")), reg(r), "{0, 0}", m)
        add("T1_X86_OR32_RM", "or %s, %s" % (R32[r], masm(m, "dword ptr")), reg(r), "{0, 0}", m)
        add("T1_X86_CMP64_RM", "cmp %s, %s" % (R[r], masm(m, "qword ptr")), reg(r), "{0, 0}", m)
    add("T1_X86_STORE64_I32", "mov %s, -2" % masm(m, "qword ptr"), "{0, 0}", imm(-2), m)
    add("T1_X86_STORE32_I32", "mov %s, 0x12345" % masm(m, "dword ptr"), "{0, 0}", imm(0x12345), m)
    add("T1_X86_INC64_M", "inc %s" % masm(m, "qword ptr"), m=m)
    add("T1_X86_DEC64_M", "dec %s" % masm(m, "qword ptr"), m=m)
    add("T1_X86_JMP_M", "jmp %s" % masm(m, "qword ptr"), m=m)
    add("T1_X86_PUSH64_M", "push %s" % masm(m, "qword ptr"), m=m)
for cc, name in enumerate(
    ["o", "no", "b", "ae", "e", "ne", "be", "a", "s", "ns", "p", "np", "l", "ge", "le", "g"]
):
    add("T1_X86_JCC + %d" % cc, "j%s ext_label" % name)
    add("T1_X86_SET8 + %d" % cc, "set%s dil" % name, reg(7))
    add("T1_X86_CMOV64 + %d" % cc, "cmov%s r10, r9" % name, reg(10), reg(9))
add("T1_X86_JMP", "jmp ext_label")
add("T1_X86_CALL_REL", "call ext_label")
add("T1_X86_RET", "ret")
add("T1_X86_POPFQ", "popfq")
add("T1_X86_MFENCE", "mfence")
add("T1_X86_MULPAIR64", "mul rdx", reg(0), reg(2))
add("T1_X86_IMULPAIR64", "imul rdx", reg(0), reg(2))

src = ".intel_syntax noprefix\n.text\n" + "".join("%s\n" % c[4] for c in cases)
d = tempfile.mkdtemp()
open(os.path.join(d, "a.s"), "w").write(src)
subprocess.check_call(["as", "--64", "-o", os.path.join(d, "a.o"), os.path.join(d, "a.s")])
out = subprocess.check_output(
    ["objdump", "-d", "-w", "-M", "intel", os.path.join(d, "a.o")]
).decode()
shutil.rmtree(d)
lines = [l for l in out.splitlines() if re.match(r"^\s+[0-9a-f]+:\t", l)]
assert len(lines) == len(cases), (len(lines), len(cases))
rows = []
for c, l in zip(cases, lines):
    parts = l.split("\t")
    hexb = parts[1].split()
    dis = parts[2].strip() if len(parts) > 2 else ""
    dis = re.sub(r"\s+", " ", dis)
    m = c[3]
    mc = (
        "NOMEM"
        if m is None
        else "{%s, %s, %d, %d}"
        % (
            "T1_X86_NOREG" if m[0] is None else "T1_" + R[m[0]].upper(),
            "T1_X86_NOREG" if m[1] is None else "T1_" + R[m[1]].upper(),
            m[2],
            m[3],
        )
    )
    rows.append(
        "    {{%s, {%s, %s}, %s}, %d, {%s}},  /* %s */"
        % (c[0], c[1], c[2], mc, len(hexb), ", ".join("0x" + h for h in hexb), dis)
    )
print("\n".join(rows))
